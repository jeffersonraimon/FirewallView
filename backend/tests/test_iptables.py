from firewallview.parsers.iptables import parse_iptables_script
from firewallview.exporters.iptables import export_to_iptables


def one(text):
    rules, _ = parse_iptables_script(text)
    assert len(rules) == 1, rules
    return rules[0]


def test_policies_and_noise():
    text = """#!/bin/bash
set -e
iptables -F
iptables -X
iptables -N MYCHAIN
iptables -P INPUT DROP
iptables -t nat -P PREROUTING ACCEPT
iptables -A INPUT -j ACCEPT
"""
    rules, _ = parse_iptables_script(text)
    assert [(r.chain, r.is_policy, r.action) for r in rules] == [
        ("input", True, "drop"), ("dstnat", True, "accept"), ("input", False, "accept")]
    assert rules[0].table == "filter" and rules[1].table == "nat"
    assert rules[0].conditions.protocol is None


def test_iptables_save_dump():
    text = """# Generated by iptables-save v1.8
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A POSTROUTING -o eth0 -j MASQUERADE
COMMIT
*filter
:INPUT DROP [0:0]
:FORWARD ACCEPT [0:0]
:MYCHAIN - [0:0]
-N MYCHAIN
-A INPUT -j MYCHAIN
-A MYCHAIN -p tcp -j ACCEPT
COMMIT
"""
    rules, _ = parse_iptables_script(text)
    pol = [r for r in rules if r.is_policy]
    assert {(r.table, r.chain, r.action) for r in pol} == {
        ("nat", "dstnat", "accept"), ("nat", "srcnat", "accept"),
        ("filter", "input", "drop"), ("filter", "forward", "accept")}
    jump = [r for r in rules if r.action == "jump"][0]
    assert jump.target_chain == "MYCHAIN"
    assert any(r.chain == "MYCHAIN" for r in rules)
    assert all(r.family == "ipv4" for r in rules)


def test_family_detection():
    assert one("ip6tables -A INPUT -j DROP").family == "ipv6"
    assert one("iptables -A INPUT -j DROP").family == "ipv4"
    r, _ = parse_iptables_script("# Generated by ip6tables-save v1.8\n*filter\n-A INPUT -j DROP\nCOMMIT\n")
    assert r[0].family == "ipv6"


def test_actions_normalised():
    assert one("iptables -t nat -A PREROUTING -j DNAT --to-destination 192.0.2.5:80").action == "dst-nat"
    assert one("iptables -t nat -A POSTROUTING -j SNAT --to-source 192.0.2.1").chain == "srcnat"
    assert one("iptables -t nat -A POSTROUTING -j MASQUERADE").action == "masquerade"
    assert one("iptables -t nat -A PREROUTING -p tcp -j REDIRECT --to-ports 3128").nat_to_ports == "3128"
    r = one("iptables -t mangle -A PREROUTING -j MARK --set-mark 0x5")
    assert (r.action, r.mark_value, r.chain) == ("mark-packet", "0x5", "prerouting")
    assert one("iptables -t mangle -A PREROUTING -j CONNMARK --set-mark 7").action == "mark-connection"
    assert one("iptables -A INPUT -j LOG --log-prefix 'x '").action == "log"
    assert one("iptables -A MYCHAIN -j RETURN").action == "return"
    r = one("iptables -t mangle -A FORWARD -p tcp -j TCPMSS --set-mss 1400")
    assert (r.action, r.mark_value) == ("change-mss", "1400")
    r = one("iptables -t nat -A PREROUTING -j NETMAP --to 198.51.100.0/24")
    assert (r.action, r.nat_to_addresses) == ("netmap", "198.51.100.0/24")
    r = one("iptables -A FORWARD -j Custom-Chain")
    assert (r.action, r.target_chain) == ("jump", "Custom-Chain")
    # rule without target is not an accept
    assert one("iptables -A INPUT -p tcp").action == "passthrough"


def test_nat_target_forms():
    r = one("ip6tables -t nat -A PREROUTING -p tcp --dport 80 -j DNAT --to-destination [2001:db8::5]:8080")
    assert (r.nat_to_addresses, r.nat_to_ports) == ("2001:db8::5", "8080")
    r = one("iptables -t nat -A PREROUTING -j DNAT --to-destination 10.0.0.1-10.0.0.5:8000-8010")
    assert (r.nat_to_addresses, r.nat_to_ports) == ("10.0.0.1-10.0.0.5", "8000-8010")
    r = one("ip6tables -t nat -A PREROUTING -j DNAT --to-destination 2001:db8::5")
    assert (r.nat_to_addresses, r.nat_to_ports) == ("2001:db8::5", None)
    r = one("iptables -t nat -A POSTROUTING -j SNAT --to-source 192.0.2.1:1024-2000")
    assert (r.nat_to_addresses, r.nat_to_ports) == ("192.0.2.1", "1024-2000")


def test_matchers():
    c = one("iptables -A INPUT -p tcp -m multiport --dports 22,80:90 -j ACCEPT").conditions
    assert c.dst_port == "22,80-90"
    c = one("iptables -A INPUT -p udp -m multiport --sports 53,123 -j ACCEPT").conditions
    assert c.src_port == "53,123"
    c = one("iptables -A INPUT -p tcp -m multiport ! --ports 1,2 -j ACCEPT").conditions
    assert c.port == "1,2" and c.negate_port
    c = one("iptables -A INPUT -m conntrack ! --ctstate NEW -j ACCEPT").conditions
    assert c.connection_state == ["new"] and c.negate_connection_state
    c = one("iptables -A INPUT -m state ! --state INVALID -j ACCEPT").conditions
    assert c.negate_connection_state
    c = one("iptables -A INPUT -m mark ! --mark 0x1 -j DROP").conditions
    assert c.packet_mark == "0x1" and c.negate_packet_mark
    c = one("iptables -A INPUT -p tcp --tcp-flags SYN,RST,ACK,FIN SYN -j DROP").conditions
    assert c.tcp_flags[0] == "syn" and set(c.tcp_flags[1:]) == {"!rst", "!ack", "!fin"}
    c = one("iptables -A INPUT -p tcp ! --syn -j DROP").conditions
    assert c.negate_tcp_flags and "syn" in c.tcp_flags
    c = one("iptables -A INPUT -m set ! --match-set BL src -j DROP").conditions
    assert c.src_address_list == "BL" and c.negate_src_address_list
    c = one("iptables -A INPUT -m set --match-set BL dst -j DROP").conditions
    assert c.dst_address_list == "BL"
    c = one("iptables -A INPUT -m limit --limit 5/min --limit-burst 10 -j ACCEPT").conditions
    assert c.limit == "5/min,10:packet"
    c = one("iptables -A INPUT ! -s 192.0.2.0/24 ! -p tcp -j DROP").conditions
    assert c.negate_src_address and c.negate_protocol


def test_unknown_goes_to_warnings():
    r = one("iptables -A INPUT -p icmp --icmp-type echo-request -j ACCEPT")
    assert any("icmp-type" in w for w in r.parse_warnings)
    r = one("iptables -A INPUT -m string --string foo --algo bm -j DROP")
    assert any("string" in w for w in r.parse_warnings)
    # iprange is modelled since the kernel-differential fixes: no warning, real range
    r = one("iptables -A INPUT -m iprange --src-range 192.0.2.1-192.0.2.9 -j DROP")
    assert r.conditions.src_address == "192.0.2.1-192.0.2.9" and not r.parse_warnings
    r = one("iptables -A INPUT -m addrtype --src-type LOCAL -j DROP")
    assert r.parse_warnings


def test_insert_position():
    text = """iptables -A INPUT -p tcp --dport 1 -j ACCEPT
iptables -A INPUT -p tcp --dport 2 -j ACCEPT
iptables -I INPUT 2 -p tcp --dport 3 -j DROP
iptables -I INPUT -p tcp --dport 4 -j DROP
"""
    rules, _ = parse_iptables_script(text)
    assert [r.conditions.dst_port for r in rules] == ["4", "1", "3", "2"]
    assert [r.order for r in rules] == [1, 2, 3, 4]


def test_exporter_basics():
    text = """iptables -t nat -A PREROUTING -p tcp --dport 80 -j DNAT --to-destination 192.0.2.5:8080
iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE
iptables -N Web-In
iptables -A FORWARD -j Web-In
iptables -A Web-In -p tcp -m multiport --dports 80,443 -j ACCEPT
iptables -A INPUT -m conntrack ! --ctstate NEW -j ACCEPT
iptables -A INPUT -m set ! --match-set BL src -j DROP
iptables -P INPUT DROP
ip6tables -A INPUT -p ipv6-icmp -j ACCEPT
"""
    rules, al = parse_iptables_script(text)
    out = export_to_iptables(rules, al)
    assert "-t nat -A PREROUTING" in out and "-t nat -A POSTROUTING" in out
    assert "iptables -N Web-In" in out
    assert "-A Web-In" in out and "-j Web-In" in out
    assert "-m multiport --dports 80,443" in out
    assert "-m conntrack ! --ctstate NEW" in out
    assert "-m set ! --match-set BL src" in out
    assert "iptables -P INPUT DROP" in out
    assert out.index("ip6tables") > out.index("iptables -P")


def test_exporter_other_actions_and_ports_without_proto():
    from firewallview.models.rules import FirewallRule, RuleCondition
    rules = [
        FirewallRule(id="1", order=1, chain="input", action="add-src-to-address-list",
                     address_list_target="SCAN", address_list_timeout="1h",
                     conditions=RuleCondition(protocol="tcp")),
        FirewallRule(id="2", order=2, chain="input", action="accept",
                     conditions=RuleCondition(dst_port="22")),
        FirewallRule(id="3", order=3, chain="forward", action="fasttrack-connection"),
        FirewallRule(id="4", order=4, table="mangle", chain="prerouting", action="mark-routing", mark_value="to_wan"),
    ]
    out = export_to_iptables(rules, {})
    assert "-j SET --add-set SCAN src --timeout 3600" in out
    assert "# warning: rule 2" in out
    assert "-p tcp --dport 22" in out and "-p udp --dport 22" in out
    assert "# unsupported: rule 3" in out
    assert "-j MARK --set-mark to_wan" in out
    assert "ipset create SCAN hash:net timeout 0" in out


def test_exporter_ipv6_nat_port():
    from firewallview.models.rules import FirewallRule, RuleCondition
    r = FirewallRule(id="1", table="nat", chain="dstnat", family="ipv6", action="dst-nat",
                     nat_to_addresses="2001:db8::5", nat_to_ports="8080",
                     conditions=RuleCondition(protocol="tcp", dst_port="80"))
    out = export_to_iptables([r], {})
    assert "ip6tables -t nat -A PREROUTING" in out
    assert "--to-destination '[2001:db8::5]:8080'" in out
    back, _ = parse_iptables_script(out)
    assert (back[0].nat_to_addresses, back[0].nat_to_ports, back[0].family) == ("2001:db8::5", "8080", "ipv6")


def test_round_trip():
    text = """iptables -P INPUT DROP
iptables -t nat -A PREROUTING -i eth0 -p tcp --dport 80 -j DNAT --to-destination 10.0.0.10:8080
iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE
iptables -N Custom
iptables -A INPUT -m conntrack ! --ctstate NEW,INVALID -j ACCEPT -m comment --comment "state ok"
iptables -A INPUT -p tcp -m multiport --dports 22,80:90 ! -s 192.0.2.0/24 -j Custom
iptables -A Custom -p tcp --tcp-flags SYN,RST,ACK,FIN SYN -m limit --limit 10/second --limit-burst 5 -j ACCEPT
iptables -A INPUT -m set --match-set BAD src -m mark ! --mark 0x2 -j DROP
iptables -t mangle -A PREROUTING -p tcp --sport 1024:2000 -j MARK --set-mark 9
ip6tables -A INPUT -s 2001:db8::/32 -j DROP
ip6tables -P FORWARD DROP
"""
    r1, a1 = parse_iptables_script(text)
    out = export_to_iptables(r1, a1)
    r2, _ = parse_iptables_script(out)
    key = lambda rs: sorted((r.table, r.chain, r.family, r.is_policy, r.action, r.target_chain,
                             r.nat_to_addresses, r.nat_to_ports, r.mark_value, r.comment,
                             r.conditions.model_dump_json()) for r in rs)
    assert len(r1) == len(r2) == 10
    assert key(r1) == key(r2)
    # second pass is stable
    out2 = export_to_iptables(r2, {})
    assert len(parse_iptables_script(out2)[0]) == 10
    assert "set -e" in out
